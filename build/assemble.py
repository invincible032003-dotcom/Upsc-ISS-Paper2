# -*- coding: utf-8 -*-
"""Assembles questions2.js from pyq_raw.json + classify_map.py + taxonomy.py + build/ans/*.py.

Run from the repository root:  python3 build/assemble.py
Writes: ISS-Statistics-II-Mock/questions2.js
"""
import json
import glob
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "ans"))

from classify_map import LM, SI, OS
from taxonomy import MICRO

MAPS = [("LM", LM), ("SI", SI), ("OS", OS)]


def load_answer_packs():
    packs = {}
    for f in sorted(glob.glob(os.path.join(HERE, "ans", "*.py"))):
        modname = os.path.basename(f)[:-3]
        mod = __import__(modname)
        for key, val in mod.A.items():
            if key in packs:
                raise SystemExit("Duplicate answer key %s in %s (already in %s)" % (key, modname, packs[key][1]))
            packs[key] = (val, modname)
    return packs


def code_for(year, qn):
    for prefix, D in MAPS:
        if qn in D.get(year, {}):
            return prefix, D[year][qn]
    return None, None


def main():
    raw = json.load(open(os.path.join(HERE, "pyq_raw.json"), encoding="utf-8"))
    packs = load_answer_packs()

    out = []
    seen_ids = set()
    missing_classification = []
    missing_answer = []

    for gid, item in enumerate(raw, start=1):
        year = item["year"]
        qn = item["questionNumber"]
        prefix, code = code_for(year, qn)
        if code is None:
            missing_classification.append((year, qn))
            continue
        unit, topic, subtopic, syllabusConcept = MICRO[code]

        akey = "%d-Q%d" % (year, qn)
        pack_entry = packs.get(akey)
        if pack_entry is None:
            missing_answer.append(akey)
            continue
        ans, modname = pack_entry

        qid = "%d-P2-Q%02d" % (year, qn)
        if qid in seen_ids:
            raise SystemExit("Duplicate id %s" % qid)
        seen_ids.add(qid)

        solution = [{"step": i + 1, "text": t} for i, t in enumerate(ans.get("sol", []))]

        record = {
            "id": qid,
            "globalId": gid,
            "year": year,
            "questionNumber": qn,
            "unit": unit,
            "topic": topic,
            "subtopic": subtopic,
            "syllabusConcept": syllabusConcept,
            "microTopic": code,
            "question": item["question"],
            "sharedStem": item.get("sharedStem", "") or "",
            "trailingNote": item.get("trailingNote", "") or "",
            "options": item["options"],
            "correctAnswer": ans["ans"],
            "questionType": ans.get("qtype", "Conceptual"),
            "difficulty": ans.get("diff", "Medium"),
            "examShortcut": ans.get("sc", ""),
            "tipsTricks": ans.get("tips", []),
            "solution": solution,
            "explanationSource": "AI-derived explanation",
            "sourceYear": year,
            "sourceQuestionNumber": qn,
            "sourceFile": item.get("sourceFile", ""),
        }
        if "flag" in ans:
            record["sourceAmbiguityNote"] = ans["flag"]

        if len(item["options"]) != 4:
            raise SystemExit("Item %s does not have exactly 4 options" % qid)
        if not (0 <= ans["ans"] <= 3):
            raise SystemExit("Item %s has out-of-range correctAnswer" % qid)

        out.append(record)

    if missing_classification:
        raise SystemExit("Missing classification for: %s" % missing_classification[:10])
    if missing_answer:
        raise SystemExit("Missing answer pack for: %s" % missing_answer[:10])

    print("Assembled %d questions (expected 720)." % len(out))
    per_year = {}
    per_unit = {}
    for r in out:
        per_year[r["year"]] = per_year.get(r["year"], 0) + 1
        per_unit[r["unit"]] = per_unit.get(r["unit"], 0) + 1
    for y in sorted(per_year):
        print(" ", y, per_year[y])
    for u in per_unit:
        print(" ", u, per_unit[u])

    out_dir = os.path.join(ROOT, "ISS-Statistics-II-Mock")
    os.makedirs(out_dir, exist_ok=True)
    js_path = os.path.join(out_dir, "questions2.js")
    with open(js_path, "w", encoding="utf-8") as f:
        f.write("// AUTO-GENERATED by build/assemble.py - do not edit by hand.\n")
        f.write("// Authentic UPSC ISS Statistics Paper II PYQs, 2018-2026 (720 items).\n")
        f.write("// All examShortcut / tipsTricks / solution content is AI-derived\n")
        f.write("// (the source booklets carry no official answer key or solutions).\n")
        f.write("window.quizDataPaper2 = ")
        json.dump(out, f, ensure_ascii=False, indent=None, separators=(",", ":"))
        f.write(";\n")
    size_kb = os.path.getsize(js_path) / 1024
    print("Wrote %s (%.1f KB)" % (js_path, size_kb))


if __name__ == "__main__":
    main()
