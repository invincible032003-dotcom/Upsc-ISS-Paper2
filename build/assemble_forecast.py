# -*- coding: utf-8 -*-
"""Assembles forecast.js (window.forecastDataPaper2) from build/forecast/*.py.

These are AI-GENERATED forecast questions - never authentic PYQs, and never
merged into questions2.js / window.quizDataPaper2. Every record carries
provenance="forecast" and isForecast=True so the UI can enforce this
separation and label them clearly.

Run from the repository root:  python3 build/assemble_forecast.py
Writes: ISS-Statistics-II-Mock/forecast.js
"""
import json
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(HERE, "forecast"))

import lm_forecast
import estimation_forecast
import hypothesis_forecast

SECTIONS = [
    ("Linear Models", "LM", lm_forecast.FORECAST),
    ("Estimation", "EST", estimation_forecast.FORECAST),
    ("Hypothesis Testing", "HT", hypothesis_forecast.FORECAST),
]


def main():
    out = []
    seen_ids = set()
    for section_name, code, items in SECTIONS:
        if len(items) != 25:
            raise SystemExit("Section %s has %d items, expected 25" % (section_name, len(items)))
        for i, item in enumerate(items, start=1):
            qid = "F-%s-%02d" % (code, i)
            if qid in seen_ids:
                raise SystemExit("Duplicate forecast id %s" % qid)
            seen_ids.add(qid)
            if len(item["options"]) != 4:
                raise SystemExit("Forecast item %s does not have exactly 4 options" % qid)
            if not (0 <= item["ans"] <= 3):
                raise SystemExit("Forecast item %s has out-of-range correctAnswer" % qid)
            # Every item in build/forecast/*.py was drafted with the correct
            # option written first for readability, which left ~74 of 75
            # correct answers sitting at position (a) - a real, exploitable
            # flaw (see the "25/25 with all-A answers" test result that
            # caught it). Deterministically (seeded on the id, so re-running
            # this script is reproducible) shuffle each item's 4 options and
            # remap correctAnswer to the shuffled position, without touching
            # the hand-verified option text or reasoning at all.
            rng = random.Random(qid)
            order = [0, 1, 2, 3]
            rng.shuffle(order)
            # order[new_pos] = old_pos: shuffled_options[new_pos] pulls from
            # the original option at old_pos; the correct answer's new
            # position is wherever its old index appears in `order`.
            shuffled_options = [item["options"][order[p]] for p in range(4)]
            shuffled_ans = order.index(item["ans"])
            solution = [{"step": j + 1, "text": t} for j, t in enumerate(item.get("sol", []))]
            record = {
                "id": qid,
                "section": section_name,
                "topic": item["topic"],
                "subtopic": item["subtopic"],
                "question": item["question"],
                "options": shuffled_options,
                "correctAnswer": shuffled_ans,
                "questionType": item.get("qtype", "Conceptual"),
                "difficulty": item.get("diff", "Medium"),
                "examShortcut": item.get("sc", ""),
                "tipsTricks": item.get("tips", []),
                "solution": solution,
                "explanationSource": "AI-derived explanation",
                "isForecast": True,
                "provenanceLabel": "FORECAST / AI-GENERATED — NOT AN AUTHENTIC PYQ",
            }
            out.append(record)

    print("Assembled %d forecast questions (expected 75)." % len(out))
    for section_name, code, items in SECTIONS:
        print(" ", section_name, len(items))

    out_dir = os.path.join(ROOT, "ISS-Statistics-II-Mock")
    os.makedirs(out_dir, exist_ok=True)
    js_path = os.path.join(out_dir, "forecast.js")
    with open(js_path, "w", encoding="utf-8") as f:
        f.write("// AUTO-GENERATED by build/assemble_forecast.py - do not edit by hand.\n")
        f.write("// AI-GENERATED FORECAST questions for 2027 - NOT authentic UPSC PYQs.\n")
        f.write("// Every item is clearly labeled and must never be merged with\n")
        f.write("// window.quizDataPaper2 (the authentic PYQ dataset in questions2.js).\n")
        f.write("window.forecastDataPaper2 = ")
        json.dump(out, f, ensure_ascii=False, indent=None, separators=(",", ":"))
        f.write(";\n")
    size_kb = os.path.getsize(js_path) / 1024
    print("Wrote %s (%.1f KB)" % (js_path, size_kb))


if __name__ == "__main__":
    main()
